#Relational or comparison operators
a=10
b=5
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)


#logical operators
x=True
y=False

print(x and y)
print(x or y)
print(not x)

#Bitwise operators
a=5
b=3

print(a & b)
print(a | b)
print(a ^ b)

a=5
print(a<<1)
print(a<<2)

a=20
print(a>>1)
print(a>>2)



#Membership operators

fruits = ["apple", "banana", "mango"]

print("apple" in fruits)
print("grape" not in fruits)


#identity operators
a = [1, 2]
b = a
c = [1, 2]
print(a is b)
print(a is c)
print(a is not c)

